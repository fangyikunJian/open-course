def plain(s):
    return TAGS.sub("", s or "")


def main():
    apply = "--apply" in sys.argv
    path = os.path.join(HERE, "episodes-L01.json")
    eps = json.loads(io.open(path, encoding="utf-8").read())
    print("%-4s %8s %8s   %s" % ("KP", "原字数", "新字数", "各栏(新)"))
    bad = 0
    for ep in eps:
        kp = ep["kp"]
        old = sum(len(plain(ep["sum"].get(k, ""))) for k in "hkmwe")
        if kp not in SUMS:
            print("%-4d %8d %8s   （未提供新卡）" % (kp, old, "-"))
            continue
        new = SUMS[kp]
        per = {k: len(plain(new.get(k, ""))) for k in "hkmwe"}
        tot = sum(per.values())
        flag = ""
        if tot > BUDGET:
            flag = "  ✗ 超预算 %d" % BUDGET
            bad += 1
        over = [k for k, v in per.items() if v > FIELD_MAX]
        if over:
            flag += "  ✗ 单栏超 %d: %s" % (FIELD_MAX, over)
            bad += 1
        print("%-4d %8d %8d   %s%s"
              % (kp, old, tot,
                 " ".join("%s:%d" % (k, per[k]) for k in "hkmwe"), flag))
        if apply:
            ep["sum"] = dict(new)
    print()
    if bad:
        print("有 %d 处超预算 —— 未写盘。" % bad)
        return 1
    if apply:
        io.open(path, "w", encoding="utf-8").write(
            json.dumps(eps, indent=2, ensure_ascii=False))
        print("全部在预算内，已写回 episodes-L01.json")
    else:
        print("全部在预算内。（空跑，加 --apply 写回）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
